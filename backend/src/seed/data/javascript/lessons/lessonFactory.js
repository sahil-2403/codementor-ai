export const makeLesson = ({
  key,
  topicKey,
  title,
  difficulty,
  theory,
  codeExample,
  codeExplanation,
  commonMistakes,
  interviewDefinition,
  interviewQuestion,
  interviewAnswer,
  interviewChecklist,
  interviewType = 'concept',
  practiceTask,
  knowledgeCheck,
  tags,
  estimatedMinutes = 45
}) => ({
  key,
  topicKey,
  title,
  difficulty,
  theory: theory.join('\n\n'),
  codeExample,
  codeExplanation,
  commonMistakes,
  interviewDefinition,
  interviewQuestions: [{ question: interviewQuestion, answer: interviewAnswer }],
  interviewChecklist,
  interviewType,
  practiceTask,
  knowledgeCheck,
  tags,
  estimatedMinutes
});
